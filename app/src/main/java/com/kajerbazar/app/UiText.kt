private fun translateKajerBazarUiText(value: String, language: String): String {
    if (language != "en") return value
    englishUiText[value]?.let { return it }
    return when {
        value.startsWith("ঘোষণা: ") -> "Announcement: " + value.removePrefix("ঘোষণা: ")
        value.startsWith("দক্ষতা: ") -> "Skills: " + value.removePrefix("দক্ষতা: ")
        value.startsWith("অবস্থা: ") -> "Status: " + value.removePrefix("অবস্থা: ")
        value.startsWith("আবেদন বার্তা: ") -> "Application Message: " + value.removePrefix("আবেদন বার্তা: ")
        value.startsWith("আবেদনের অবস্থা: ") -> "Application Status: " + value.removePrefix("আবেদনের অবস্থা: ")
        value.startsWith("মজুরি: ") -> "Wage: " + value.removePrefix("মজুরি: ")
        value.startsWith("কর্মীর মজুরি: ") -> "Worker's Wage: " + value.removePrefix("কর্মীর মজুরি: ")
        value.startsWith("প্রত্যাশিত মজুরি: ") -> "Expected Wage: " + value.removePrefix("প্রত্যাশিত মজুরি: ")
        value.startsWith("দেখানো হচ্ছে: ") -> "Showing: " + value.removePrefix("দেখানো হচ্ছে: ")
        value.startsWith("অপেক্ষমাণ কাজ: ") -> "Pending Jobs: " + value.removePrefix("অপেক্ষমাণ কাজ: ")
        value.startsWith("কাজদাতা আবেদন: ") -> "Employer Applications: " + value.removePrefix("কাজদাতা আবেদন: ")
        value.startsWith("ব্যবহারকারী পরিচালনা (") -> "Manage Users (" + value.substringAfter("ব্যবহারকারী পরিচালনা (")
        else -> value
    }
}

@Composable
fun Text(
    text: String,
    modifier: Modifier = Modifier,
    color: Color = Color.Unspecified,
    fontSize: TextUnit = TextUnit.Unspecified,
    fontStyle: FontStyle? = null,
    fontWeight: FontWeight? = null,
    fontFamily: FontFamily? = null,
    letterSpacing: TextUnit = TextUnit.Unspecified,
    textDecoration: TextDecoration? = null,
    textAlign: TextAlign? = null,
    lineHeight: TextUnit = TextUnit.Unspecified,
    overflow: TextOverflow = TextOverflow.Clip,
    softWrap: Boolean = true,
    maxLines: Int = Int.MAX_VALUE,
    minLines: Int = 1,
    onTextLayout: (TextLayoutResult) -> Unit = {},
    style: TextStyle = LocalTextStyle.current
) {
    val context = LocalContext.current
    val language = context.getSharedPreferences("kajer_bazar_preferences", android.content.Context.MODE_PRIVATE)
        .getString("app_language", "bn") ?: "bn"
    MaterialText(
        text = translateKajerBazarUiText(text, language),
        modifier = modifier,
        color = color,
        fontSize = fontSize,
        fontStyle = fontStyle,
        fontWeight = fontWeight,
        fontFamily = fontFamily,
        letterSpacing = letterSpacing,
        textDecoration = textDecoration,
        textAlign = textAlign,
        lineHeight = lineHeight,
        overflow = overflow,
        softWrap = softWrap,
        maxLines = maxLines,
        minLines = minLines,
        onTextLayout = onTextLayout,
        style = style
    )
}
